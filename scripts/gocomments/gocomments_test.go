package gocomments

import (
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

func TestLines(t *testing.T) {
	tests := []struct {
		name string
		src  string
		want []int
	}{
		{"line, trailing and block comments", "package p\n\n// one\n// two\nvar a = 1 // three\n\n/* four\nstill four */\nvar b = 2\n", []int{3, 4, 5, 7}},
		{"license header", "// Copyright (c) 2025-2026, s0up and the autobrr contributors.\n// SPDX-License-Identifier: GPL-2.0-or-later\n\npackage p\n", nil},
		{"compiler and linter directives", "//go:build linux\n\npackage p\n\nimport _ \"embed\"\n\n//go:embed x\nvar x string\n\n//nolint:gosec // reason\nvar y = 1 //exhaustive:ignore\n", nil},
		{"gosec and deprecation markers", "package p\n\n// Deprecated: use g.\nfunc f() {}\n\n// #nosec G304 -- reason\nvar a = 1 // #nosec G115\n", nil},
		{"end of an Experimental feature", "package p\n\nvar known = []Feature{\n\ta, // goes away in #1\n\tb, // goes away when the maintainer decides, with no ticket\n}\n", nil},
		{"not a directive", "package p\n\n// see nolint:gosec\n// regression: #1\n// goes away after the preview\nvar a = 1\n", []int{3, 4, 5}},
		{"generated file", "// Code generated by x. DO NOT EDIT.\n\npackage p\n\n// one\nvar a = 1\n", nil},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, err := Lines("p.go", []byte(tt.src))
			require.NoError(t, err)
			assert.Equal(t, tt.want, got)
		})
	}
}
