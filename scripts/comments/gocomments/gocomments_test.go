func TestCount(t *testing.T) {
	tests := []struct {
		name string
		src  string
		want int
	}{
		{"line, trailing and block comments", "package p\n\n// one\n// two\nvar a = 1 // three\n\n/* four\nstill four */\nvar b = 2\n", 4},
		{"license header", "// Copyright (c) 2025-2026, s0up and the autobrr contributors.\n// SPDX-License-Identifier: GPL-2.0-or-later\n\npackage p\n", 0},
		{"compiler and linter directives", "//go:build linux\n\npackage p\n\nimport _ \"embed\"\n\n//go:embed x\nvar x string\n\n//nolint:gosec // reason\nvar y = 1 //exhaustive:ignore\n", 0},
		{"gosec and deprecation markers", "package p\n\n// Deprecated: use g.\nfunc f() {}\n\n// #nosec G304 -- reason\nvar a = 1 // #nosec G115\n", 0},
		{"regression marker", "package p\n\n// regression: #3726\nfunc f() {}\n", 0},
		{"prose about a directive", "package p\n\n// see nolint:gosec\n// regression test\nvar a = 1\n", 2},
		{"generated file", "// Code generated by x. DO NOT EDIT.\n\npackage p\n\n// one\nvar a = 1\n", 0},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, err := Count("p.go", []byte(tt.src))
			require.NoError(t, err)
			assert.Equal(t, tt.want, got)
		})
	}
}

func TestBlocks(t *testing.T) {
	src := "package p\n\n// one\n// two\nfunc f() {\n\tg() // three\n\t// four\n\n\t// five\n\t//nolint:errcheck // reason\n\tg()\n}\n"
	got, err := Blocks("p.go", []byte(src))
	require.NoError(t, err)
	for i := range got {
		got[i].comments = nil
	}
	assert.Equal(t, []Block{
		{File: "p.go", Line: 3, End: 4, Text: "// one\n// two"},
		{File: "p.go", Line: 6, End: 6, Trailing: true, Text: "// three"},
		{File: "p.go", Line: 7, End: 7, Text: "// four"},
		{File: "p.go", Line: 9, End: 9, Text: "// five"},
	}, got)
}

func TestStrip(t *testing.T) {
	tests := []struct {
		name   string
		src    string
		doomed []Block
		want   string
	}{
		{
			"a doc comment and a trailing comment",
			"package p\n\n// f does it.\n// Really.\nfunc f() {\n\tg() // call g\n}\n",
			[]Block{{Line: 3, Text: "// f does it.\n// Really."}, {Line: 6, Text: "// call g"}},
			"package p\n\nfunc f() {\n\tg()\n}\n",
		},
		{
			"the blank line that a comment leaves at the edge of a block goes too",
			"package p\n\nfunc f() {\n\t// first\n\n\tg()\n\n\t// last\n}\n",
			[]Block{{Line: 4, Text: "// first"}, {Line: 8, Text: "// last"}},
			"package p\n\nfunc f() {\n\tg()\n}\n",
		},
		{
			"a comment between two statements leaves one blank line",
			"package p\n\nfunc f() {\n\tg()\n\n\t// then\n\n\tg()\n}\n",
			[]Block{{Line: 6, Text: "// then"}},
			"package p\n\nfunc f() {\n\tg()\n\n\tg()\n}\n",
		},
		{
			"a block that is not named stays",
			"package p\n\n// keep\nvar a = 1 // drop\n",
			[]Block{{Line: 4, Text: "// drop"}},
			"package p\n\n// keep\nvar a = 1\n",
		},
		{
			"a comment in front of code on its line",
			"package p\n\nvar a = /* one */ 1\n",
			[]Block{{Line: 3, Text: "/* one */"}},
			"package p\n\nvar a = 1\n",
		},
		{
			"two comments after the code on one line",
			"package p\n\nvar a = 1 /* first */ /* second */\n",
			[]Block{{Line: 3, Text: "/* first */"}, {Line: 3, Text: "/* second */"}},
			"package p\n\nvar a = 1\n",
		},
		{
			"the same comment twice on one line",
			"package p\n\nvar n = /* same */ 1 + /* same */ 2\n",
			[]Block{{Line: 3, Text: "/* same */"}, {Line: 3, Text: "/* same */"}},
			"package p\n\nvar n = 1 + 2\n",
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, missed, err := Strip("p.go", []byte(tt.src), tt.doomed)
			require.NoError(t, err)
			assert.Empty(t, missed)
			assert.Equal(t, tt.want, string(got))
		})
	}
}

func TestStripSkipsABlockWhoseTextMoved(t *testing.T) {
	src := "package p\n\n// now different\nvar a = 1\n"
	doomed := []Block{{Line: 3, Text: "// old text"}}
	got, missed, err := Strip("p.go", []byte(src), doomed)
	require.NoError(t, err)
	assert.Equal(t, doomed, missed)
	assert.Equal(t, src, string(got))
}

func TestSameCode(t *testing.T) {
	assert.True(t, SameCode([]byte("package p\n\n// one\nvar a = 1 // two\n"), []byte("package p\n\nvar a = 1\n")))
	assert.False(t, SameCode([]byte("package p\n\nvar a = 1\n"), []byte("package p\n\nvar a = 2\n")))
	assert.False(t, SameCode([]byte("package p\n\nvar a = \"// one\"\n"), []byte("package p\n\nvar a = \"\"\n")))
}
