type closedSet struct {
	name   string
	values []string
}

func readTypedConstants(dir, typeName string) ([]string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	var values []string
	fset := token.NewFileSet()
	for _, entry := range entries {
		name := entry.Name()
		if entry.IsDir() || filepath.Ext(name) != ".go" || strings.HasSuffix(name, "_test.go") {
			continue
		}
		file, err := parser.ParseFile(fset, filepath.Join(dir, name), nil, parser.SkipObjectResolution)
		if err != nil {
			return nil, err
		}
		for _, decl := range file.Decls {
			block, ok := decl.(*ast.GenDecl)
			if !ok || block.Tok != token.CONST {
				continue
			}
			found, err := typedBlockValues(block, typeName)
			if err != nil {
				return nil, err
			}
			values = append(values, found...)
		}
	}
	if len(values) == 0 {
		return nil, fmt.Errorf("%s: no exported constant of type %s", dir, typeName)
	}
	return values, nil
}

func typedBlockValues(block *ast.GenDecl, typeName string) ([]string, error) {
	isTyped := func(spec *ast.ValueSpec) bool {
		ident, ok := spec.Type.(*ast.Ident)
		return ok && ident.Name == typeName
	}
	if !slices.ContainsFunc(block.Specs, func(s ast.Spec) bool { return isTyped(s.(*ast.ValueSpec)) }) {
		return nil, nil
	}
	var values []string
	for _, s := range block.Specs {
		spec := s.(*ast.ValueSpec)
		if spec.Type == nil {
			return nil, fmt.Errorf("%s has no type in a const block of %s, so it drops out of the %s list: give it the type", spec.Names[0].Name, typeName, typeName)
		}
		if !isTyped(spec) {
			continue
		}
		for i, name := range spec.Names {
			if !name.IsExported() {
				continue
			}
			var lit *ast.BasicLit
			if i < len(spec.Values) {
				lit, _ = spec.Values[i].(*ast.BasicLit)
			}
			if lit == nil || lit.Kind != token.STRING {
				return nil, fmt.Errorf("%s of type %s has a value that is not a string literal", name.Name, typeName)
			}
			value, err := strconv.Unquote(lit.Value)
			if err != nil {
				return nil, fmt.Errorf("%s: %w", name.Name, err)
			}
			values = append(values, value)
		}
	}
	return values, nil
}

func closedSets(root string) ([]closedSet, error) {
	kinds, err := readTypedConstants(filepath.Join(root, filepath.FromSlash(activityPackage)), "Kind")
	if err != nil {
		return nil, err
	}
	modelsDir := filepath.Join(root, filepath.FromSlash(modelsPackage))
	actions, err := readTypedConstants(modelsDir, "ActivityAction")
	if err != nil {
		return nil, err
	}
	outcomes, err := readTypedConstants(modelsDir, "ActivityOutcome")
	if err != nil {
		return nil, err
	}
	operators := make([]string, len(operatorDocs))
	for i, o := range operatorDocs {
		operators[i] = string(o.op)
	}
	fields := make([]string, 0, len(automations.ConditionFields))
	for _, field := range slices.Sorted(maps.Keys(automations.ConditionFields)) {
		fields = append(fields, string(field))
	}
	sets := []closedSet{
		{"ActivityEventKind", kinds},
		{"AutomationActivityAction", actions},
		{"AutomationActivityOutcome", outcomes},
		{"ConditionField", fields},
		{"ConditionOperator", operators},
	}

	named := map[string][]string{}
	for key, list := range keyValues {
		if list.tsName == "" {
			continue
		}
		if other, ok := named[list.tsName]; ok && !slices.Equal(other, list.values) {
			return nil, fmt.Errorf("keyValues gives %s two different lists, one at %s", list.tsName, key)
		}
		named[list.tsName] = list.values
	}
	for name, values := range named {
		sets = append(sets, closedSet{name, values})
	}
	slices.SortFunc(sets, func(a, b closedSet) int { return cmp.Compare(a.name, b.name) })
	return sets, nil
}

func generateClosedSets(root string) ([]byte, error) {
	sets, err := closedSets(root)
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	b.WriteString(`/*
 * Copyright (c) 2025-2026, s0up and the autobrr contributors.
 * SPDX-License-Identifier: GPL-2.0-or-later
 */

// Code generated by internal/automationsgen from the Go closed sets. DO NOT EDIT.
// Run "make generate" to update it.
`)
	for _, set := range sets {
		list := screamingSnake(set.name) + "_VALUES"
		b.WriteString("\n")
		writeTSList(&b, list, set.values)
		fmt.Fprintf(&b, "export type %s = (typeof %s)[number]\n", set.name, list)
	}
	b.WriteString("\n")
	writeTSList(&b, "ACTION_RUN_ORDER", automations.ActionRunOrder)
	return b.Bytes(), nil
}

func writeTSList(b *bytes.Buffer, name string, values []string) {
	fmt.Fprintf(b, "export const %s = [\n", name)
	for _, v := range values {
		fmt.Fprintf(b, "  %s,\n", tsString(v))
	}
	b.WriteString("] as const\n")
}

func screamingSnake(name string) string {
	var b strings.Builder
	for i, r := range name {
		if i > 0 && unicode.IsUpper(r) {
			b.WriteByte('_')
		}
		b.WriteRune(unicode.ToUpper(r))
	}
	return b.String()
}
