func TestArrIDCacheIsIncompleteMigrationSQLite(t *testing.T) {
	t.Parallel()

	conn, err := sql.Open("sqlite", filepath.Join(t.TempDir(), "test.db")+"?"+sqliteTimeParams)
	require.NoError(t, err)
	t.Cleanup(func() { require.NoError(t, conn.Close()) })
	checkArrIDCacheIsIncompleteMigration(t.Context(), t, conn, migrationsFS, "migrations/129_add_arr_id_cache_is_incomplete.sql", true)
}

