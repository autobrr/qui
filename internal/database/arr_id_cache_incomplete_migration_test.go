func checkArrIDCacheIsIncompleteMigration(ctx context.Context, t *testing.T, conn *sql.DB, fsys fs.ReadFileFS, migration string, isSQLite bool) {
	t.Helper()

	idCol := "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
	if isSQLite {
		idCol = "INTEGER PRIMARY KEY AUTOINCREMENT"
	}
	legacySchema := `
		CREATE TABLE arr_id_cache (
			id ` + idCol + `,
			title_hash TEXT NOT NULL,
			content_type TEXT NOT NULL,
			arr_instance_id INTEGER,
			imdb_id TEXT,
			tmdb_id INTEGER,
			tvdb_id INTEGER,
			tvmaze_id INTEGER,
			titles_json TEXT,
			episode_map_season INTEGER,
			episode_map_episode INTEGER,
			episode_map_absolute INTEGER,
			episode_map_known INTEGER NOT NULL DEFAULT 0,
			is_negative INTEGER DEFAULT 0,
			cached_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
			expires_at TIMESTAMP NOT NULL,
			UNIQUE(title_hash, content_type)
		);
	`
	_, err := conn.ExecContext(ctx, legacySchema)
	require.NoError(t, err)

	now := time.Now().UTC().Truncate(time.Second)
	rows := []struct {
		hash      string
		negative  int
		cachedAt  time.Time
		expiresAt time.Time
	}{
		{hash: "partial", negative: 0, cachedAt: now, expiresAt: now.Add(10 * time.Minute)},
		{hash: "negative-near-expiry", negative: 1, cachedAt: now.Add(-55 * time.Minute), expiresAt: now.Add(5 * time.Minute)},
		{hash: "full-near-expiry", negative: 0, cachedAt: now.Add(-29*24*time.Hour - 23*time.Hour - 55*time.Minute), expiresAt: now.Add(5 * time.Minute)},
	}
	if isSQLite {
		for _, row := range rows {
			_, err := conn.ExecContext(ctx,
				"INSERT INTO arr_id_cache (title_hash, content_type, is_negative, cached_at, expires_at) VALUES (?, 'tv', ?, ?, ?)",
				row.hash, row.negative, row.cachedAt, row.expiresAt,
			)
			require.NoError(t, err)
		}
	} else {
		for _, row := range rows {
			_, err := conn.ExecContext(ctx,
				"INSERT INTO arr_id_cache (title_hash, content_type, is_negative, cached_at, expires_at) VALUES ($1, 'tv', $2, $3, $4)",
				row.hash, row.negative, row.cachedAt, row.expiresAt,
			)
			require.NoError(t, err)
		}
	}

	body, err := fsys.ReadFile(migration)
	require.NoError(t, err)
	_, err = conn.ExecContext(ctx, string(body))
	require.NoError(t, err)

	for _, want := range []struct {
		hash         string
		isIncomplete int
	}{
		{hash: "partial", isIncomplete: 1},
		{hash: "negative-near-expiry", isIncomplete: 0},
		{hash: "full-near-expiry", isIncomplete: 0},
	} {
		query := "SELECT is_incomplete FROM arr_id_cache WHERE title_hash = ?"
		if !isSQLite {
			query = "SELECT is_incomplete FROM arr_id_cache WHERE title_hash = $1"
		}
		var got int
		require.NoError(t, conn.QueryRowContext(ctx, query, want.hash).Scan(&got), want.hash)
		require.Equal(t, want.isIncomplete, got, want.hash)
	}
}
