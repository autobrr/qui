-- Transfer history (ADR 0052). No table has a foreign key to instances: the
-- history of an instance stays when the user removes the instance. Hours and
-- days are integer counts of UTC hours and days since 1970-01-01.

-- writes counts the writes that stored the instance, so that a write whose
-- commit returns an error can tell whether it is stored.
CREATE TABLE IF NOT EXISTS transfer_history_instances (
    instance_id       INTEGER PRIMARY KEY,
    name              TEXT NOT NULL,
    first_recorded_at TIMESTAMP NOT NULL,
    last_reading_at   TIMESTAMP NOT NULL,
    writes            BIGINT NOT NULL
);

-- One record for each torrent that qui saw. private is NULL when qBittorrent
-- does not report it. statistics_cross_seed is NULL until the torrent
-- completes. upload_first_24h is NULL when qui first saw the torrent after
-- its first 24 hours. The Baseline stays under baseline_tracker_domain and
-- baseline_category, the values at the first sight of the torrent.
CREATE TABLE IF NOT EXISTS transfer_history_torrents (
    id                    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instance_id           INTEGER NOT NULL,
    hash                  TEXT NOT NULL,
    name                  TEXT NOT NULL,
    tracker_domain        TEXT NOT NULL,
    category              TEXT NOT NULL,
    private               BOOLEAN,
    size                  BIGINT NOT NULL,
    release_group         TEXT NOT NULL,
    resolution            TEXT NOT NULL,
    source                TEXT NOT NULL,
    content_type          TEXT NOT NULL,
    statistics_cross_seed BOOLEAN,
    upload_first_24h      BIGINT,
    baseline_uploaded     BIGINT NOT NULL,
    baseline_downloaded   BIGINT NOT NULL,
    baseline_tracker_domain TEXT NOT NULL,
    baseline_category     TEXT NOT NULL,
    UNIQUE (instance_id, hash)
);

-- The last counter values of each torrent. They change at each write, so
-- they live apart from the wide record.
CREATE TABLE IF NOT EXISTS transfer_history_counters (
    torrent_id INTEGER PRIMARY KEY REFERENCES transfer_history_torrents(id) ON DELETE CASCADE,
    uploaded   BIGINT NOT NULL,
    downloaded BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS transfer_history_torrent_days (
    torrent_id INTEGER NOT NULL REFERENCES transfer_history_torrents(id) ON DELETE CASCADE,
    day        INTEGER NOT NULL,
    uploaded   BIGINT NOT NULL,
    downloaded BIGINT NOT NULL,
    PRIMARY KEY (torrent_id, day)
);

-- public is true for a torrent that qBittorrent reports as not private.
CREATE TABLE IF NOT EXISTS transfer_history_tracker_hours (
    instance_id           INTEGER NOT NULL,
    hour                  INTEGER NOT NULL,
    tracker_domain        TEXT NOT NULL,
    public                BOOLEAN NOT NULL,
    statistics_cross_seed BOOLEAN NOT NULL,
    uploaded              BIGINT NOT NULL,
    downloaded            BIGINT NOT NULL,
    PRIMARY KEY (instance_id, hour, tracker_domain, public, statistics_cross_seed)
);

CREATE TABLE IF NOT EXISTS transfer_history_category_days (
    instance_id           INTEGER NOT NULL,
    day                   INTEGER NOT NULL,
    tracker_domain        TEXT NOT NULL,
    public                BOOLEAN NOT NULL,
    category              TEXT NOT NULL,
    statistics_cross_seed BOOLEAN NOT NULL,
    uploaded              BIGINT NOT NULL,
    downloaded            BIGINT NOT NULL,
    PRIMARY KEY (instance_id, day, tracker_domain, public, category, statistics_cross_seed)
);

-- The length of each Recording gap, on the hour of the reading that ended it.
CREATE TABLE IF NOT EXISTS transfer_history_gaps (
    instance_id INTEGER NOT NULL,
    hour        INTEGER NOT NULL,
    seconds     BIGINT NOT NULL,
    PRIMARY KEY (instance_id, hour)
);
