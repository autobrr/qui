-- Transfer history events: one row for each add, each completion,
-- and each delete of a torrent. second counts the seconds since 1970-01-01
-- UTC. The columns from uploaded to cause_name are NULL unless kind is
-- 'delete'. ratio and seeding_seconds are also NULL when qui did not read the
-- torrent between its start and the delete. cause_name is the name of the
-- automation rule or of the Client Proxy API key.
CREATE TABLE IF NOT EXISTS transfer_history_events (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instance_id     INTEGER NOT NULL,
    torrent_id      INTEGER NOT NULL REFERENCES transfer_history_torrents(id) ON DELETE CASCADE,
    kind            TEXT NOT NULL,
    second          BIGINT NOT NULL,
    uploaded        BIGINT,
    downloaded      BIGINT,
    ratio           DOUBLE PRECISION,
    seeding_seconds BIGINT,
    cause_kind      TEXT,
    cause_name      TEXT
);

-- cause_kind is in the index so that the count of each kind of cause reads
-- the index only.
CREATE INDEX IF NOT EXISTS idx_transfer_history_events_period
    ON transfer_history_events (instance_id, kind, second, cause_kind);

CREATE INDEX IF NOT EXISTS idx_transfer_history_events_torrent
    ON transfer_history_events (torrent_id);

-- deleted is true while the torrent is not in qBittorrent. completed is true
-- when the torrent completed since the user added it last, so that each life
-- of a torrent gets one completion event.
ALTER TABLE transfer_history_torrents ADD COLUMN deleted BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE transfer_history_torrents ADD COLUMN completed BOOLEAN NOT NULL DEFAULT FALSE;

UPDATE transfer_history_torrents SET completed = TRUE WHERE statistics_cross_seed IS NOT NULL;

-- The Statistics cross-seed flag of the Baseline: the flag of the first life
-- of the torrent. NULL while the torrent is in its first life, where the
-- Baseline follows statistics_cross_seed.
ALTER TABLE transfer_history_torrents ADD COLUMN baseline_statistics_cross_seed BOOLEAN;
